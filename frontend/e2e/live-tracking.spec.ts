test("NWS alerts draw and hover in Live Tracking, with independent panel settings", async ({ page, consoleMessages }) => {
  await page.goto("/");
  await page.getByRole("navigation", { name: "Workspaces" }).getByRole("button", { name: "Model Viewer", exact: true }).click();
  await waitForMapDrawn(page);
  await turnOn(page, "warnings");
  await expect(page.getByTestId("warning-shown")).toContainText("1 active warning");
  await turnOn(page, "watches");
  await expect(page.getByTestId("watch-shown")).toContainText("1 active watch");
  await page.getByRole("group", { name: "Map detail views" }).getByRole("button", { name: "Layers", exact: true }).click();
  await expect.poll(() => deckLayers(page)).toContain("warnings");
  await nextFrames(page);
  await hoverAt(page, -97.7, 34.5);
  const tooltip = page.getByTestId("outlook-tooltip");
  await expect(tooltip).toContainText("Tornado Warning");
  await expect(tooltip).toContainText("NWS KOUN");
  await expect(tooltip).toContainText("Issued 2026-10-04 20:45Z · Expires 2026-10-04 22Z");
  await page.getByRole("button", { name: "Two synchronized panels", exact: true }).click();
  await page.getByTestId("panel-chip-2").click();
  const second = await layerRow(page, "warnings");
  await expect(second.getByRole("switch")).toHaveAttribute("aria-checked", "false");
  await page.getByTestId("panel-chip-1").click();
  await expect(page.getByTestId("layer-row-warnings").getByRole("switch")).toHaveAttribute("aria-checked", "true");
  expectWarnings(consoleMessages, []);
});
