test("radar site labels toggle and persist on the flat live map", async ({ page, consoleMessages }) => {
  await page.goto("/");
  await page.getByRole("navigation", { name: "Workspaces" }).getByRole("button", { name: "Model Viewer", exact: true }).click();
  await waitForMapDrawn(page);
  await page.getByRole("button", { name: "Live Tracking", exact: true }).click();
  await expect.poll(() => deckLayers(page)).toContain("radar-site-labels");
  await page.getByRole("button", { name: "Layers", exact: true }).click();
  await page.getByRole("button", { name: "Map details", exact: true }).click();
  const toggle = page.getByRole("switch", { name: "Radar site labels", exact: true });
  await expect(toggle).toHaveAttribute("aria-checked", "true");
  await toggle.click();
  await expect.poll(() => deckLayers(page)).not.toContain("radar-site-labels");
  await expect.poll(() => page.evaluate(() => localStorage.getItem("sharppy.prefs.v1"))).toContain('"radar-site-labels":{"visible":false');
  await page.reload();
  await page.getByRole("navigation", { name: "Workspaces" }).getByRole("button", { name: "Model Viewer", exact: true }).click();
  await waitForMapDrawn(page);
  await page.getByRole("button", { name: "Live Tracking", exact: true }).click();
  await page.getByRole("button", { name: "Layers", exact: true }).click();
  await expect(toggle).toHaveAttribute("aria-checked", "false");
  await toggle.click();
  await expect(page.getByRole("button", { name: "Globe", exact: true })).toBeDisabled();
  await expect.poll(() => deckLayers(page)).toContain("radar-site-labels");
  await saveScreenshot(page, "browser-radar-site-labels.png");
  expectWarnings(consoleMessages, []);
});

test("Live Tracking forces a flat map and restores Model Viewer's saved Globe setting", async ({ page, consoleMessages }) => {
  test.setTimeout(120_000); // Four software-rendered globes and a reload exceed a minute on hosted Windows.
  await page.goto("/");
  await page.getByRole("navigation", { name: "Workspaces" }).getByRole("button", { name: "Model Viewer", exact: true }).click();
  await waitForMapDrawn(page);
  await page.getByRole("button", { name: "Four synchronized panels", exact: true }).click();
  await page.getByRole("button", { name: "Layers", exact: true }).click();
  await page.getByRole("button", { name: "Map details", exact: true }).click();
  const globe = page.getByRole("button", { name: "Globe", exact: true });
  const flat = page.getByRole("button", { name: "Flat map", exact: true });
  const projection = () => page.evaluate(() => window.__SHARPPY_E2E__?.projection());
  await globe.click();
  await expect.poll(projection).toBe("globe");
  await expect.poll(() => page.evaluate(() => localStorage.getItem("sharppy.prefs.v1"))).toContain('"projection":"globe"');
  await page.reload();
  await page.getByRole("navigation", { name: "Workspaces" }).getByRole("button", { name: "Model Viewer", exact: true }).click();
  await waitForMapDrawn(page);
  await expect.poll(projection).toBe("globe");
  await page.getByRole("button", { name: "Live Tracking", exact: true }).click();
  await page.getByRole("button", { name: "Layers", exact: true }).click();
  await expect(globe).toBeDisabled();
  await expect(flat).toHaveAttribute("aria-pressed", "true");
  await expect.poll(projection).toBe("mercator");
  await expect(page.getByTestId("map-panel-4")).toBeVisible();
  await flat.click();
  await saveScreenshot(page, "browser-live-tracking-flat-only.png");
  await page.getByRole("button", { name: "Model Viewer", exact: true }).click();
  await expect(globe).toBeEnabled();
  await expect(globe).toHaveAttribute("aria-pressed", "true");
  await expect.poll(projection).toBe("globe");
  expectWarnings(consoleMessages, []);
});

test("Live Tracking ignores map clicks and preserves Model Viewer's point", async ({ page, consoleMessages }) => {
  await page.goto("/");
  await page.getByRole("navigation", { name: "Workspaces" }).getByRole("button", { name: "Model Viewer", exact: true }).click();
  await waitForMapDrawn(page);
  const point = await projectPoint(page, -108, 36);
  expect(point).not.toBeNull();
  if (point === null) throw new Error("Forecast point is outside the map");
  await page.mouse.click(point.x, point.y);
  const inspector = page.getByRole("complementary", { name: "Inspector" });
  await expect(inspector).toContainText("Forecast point");
  const coordinates = await inspector.locator("p").filter({ hasText: /° N/u }).innerText();
  const rail = page.getByRole("navigation", { name: "Workspaces" });
  await rail.getByRole("button", { name: "Live Tracking", exact: true }).click();
  await expect(page.getByRole("button", { name: "Point details", exact: true })).toHaveCount(0);
  await expect(inspector).toHaveCount(0);
  await expect.poll(() => deckLayers(page)).not.toContain("selection-point");
  await page.mouse.click(point.x + 20, point.y + 20);
  await nextFrames(page);
  await expect(inspector).toHaveCount(0);
  await expect.poll(() => deckLayers(page)).not.toContain("selection-point");
  await saveScreenshot(page, "browser-live-tracking-no-point.png");
  await rail.getByRole("button", { name: "Model Viewer", exact: true }).click();
  await expect(page.getByRole("button", { name: "Point details", exact: true })).toBeVisible();
  await expect(inspector).toContainText("Forecast point");
  await expect(inspector).toContainText(coordinates);
  await expect.poll(() => deckLayers(page)).toContain("selection-point");
  expectWarnings(consoleMessages, []);
});

